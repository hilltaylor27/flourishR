
test_that('lags use exact waves and preserve row order', {
  d <- data.frame(ID=c(1,2,1,2,1),wave=c(3,1,1,3,2),x=c(9,4,2,8,5))
  r <- create_lags(d,'x')
  expect_equal(r$x_lag1,c(5,NA,NA,NA,2))
  expect_equal(create_lags(d,'x',lag=2)$x_lag2,c(2,NA,NA,4,NA))
  expect_equal(r$ID,d$ID)
  expect_error(create_lags(r,'x'),'already exist')
  expect_error(create_lags(rbind(d,d[1,]),'x'),'unique')
  expect_error(create_lags(d,'x',lag=0))
})
test_that('change is later minus earlier', {
  d <- data.frame(ID=c(1,1,2,3),wave=c(1,3,3,1),x=c(2,5,7,4))
  r <- change_scores(d,'x')
  expect_equal(r$ID,c(1,2))
  expect_equal(r$x_change_1_3,c(3,NA))
  expect_error(change_scores(d,'x',from=3,to=1))
})
test_that('within and between components reconstruct observations', {
  d <- data.frame(ID=c(1,1,1,2,2),wave=c(1,2,3,1,2),x=c(2,4,NA,NA,NA))
  r <- within_between(d,'x')
  expect_equal(r$x_between,c(3,3,3,NA,NA))
  expect_equal(r$x_within,c(-1,1,NA,NA,NA))
  expect_equal(r$x_between+r$x_within,d$x)
})
test_that('survey options can be scoped and validated', {
  old <- options('survey.lonely.psu')
  on.exit(options(old))
  previous <- set_lonely_psu('adjust')
  expect_identical(getOption('survey.lonely.psu'),'adjust')
  options(previous)
  expect_identical(options('survey.lonely.psu'),old)
  expect_error(set_lonely_psu('invalid'))
})
test_that('prospective regression uses longitudinal weights', {
  skip_if_not_installed('survey')
  d <- data.frame(ID=1:12, COUNTRY='Japan', wave=3, WAVE=3, STRATA=rep(1:3,each=4), PSU=1:12, ANNUAL_WEIGHT_L3=c(rep(1,11),NA), x=1:12, y=c(2,4,5,7,8,9,12,13,14,17,18,20))
  r <- loop_longitudinal(d,y~x,lonely_psu='adjust')
  fit <- survey::svyglm(y~x,design=gfs_design(d,'Japan',waves=1:3,type='longitudinal'))
  expect_equal(r$estimate,unname(stats::coef(fit)))
  expect_true(all(r$n==11))
  expect_true(all(r$weight=='ANNUAL_WEIGHT_L3'))
  expect_true(all(r$status=='ok'))
})
