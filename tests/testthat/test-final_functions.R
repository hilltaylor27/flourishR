
test_that('context joins preserve rows and reject duplicate keys', {
  d <- data.frame(COUNTRY=c(1,9,1),x=1:3)
  c <- data.frame(COUNTRY=c('Japan','Argentina'),z=c(4,8))
  expect_equal(join_country_data(d,c)$z,c(8,4,8))
  expect_error(join_country_data(d,rbind(c,c)),'one nonmissing')
  expect_error(join_country_data(d,c[1,]),'Unmatched')
})
test_that('meta regression returns moderator coefficients', {
  skip_if_not_installed('metafor')
  d <- data.frame(COUNTRY=letters[1:8],term='x',estimate=c(.1,.3,.2,.5,.4,.6,.5,.8),std.error=.1,status='ok',z=1:8)
  r <- meta_countries(d,'x',moderators=~z)
  expect_equal(r$k,rep(8L,2))
  expect_true('z' %in% r$moderator)
  expect_true(r$estimate[r$moderator=='z']>0)
})
test_that('mixed mode agrees with direct random intercept regression', {
  skip_if_not_installed('lme4')
  set.seed(42)
  d <- data.frame(ID=rep(1:40,each=3),COUNTRY='Japan',wave=rep(1:3,40),x=stats::rnorm(120))
  d$y <- d$x+rep(stats::rnorm(40),each=3)+stats::rnorm(120)
  r <- loop_longitudinal(d,y~x,model='mixed')
  f <- lme4::lmer(y~x+(1|ID),data=d)
  expect_equal(r$estimate,unname(lme4::fixef(f)))
  expect_equal(r$n_people,rep(40L,2))
  expect_true(all(r$status=='ok'))
})
test_that('plots accept analytical output', {
  d <- data.frame(COUNTRY=c('Japan','Argentina'),wave=1,variable='x',mean=c(4,5),conf.low=c(3,4),conf.high=c(5,6),status='ok')
  expect_s3_class(plot_cross_national(d,'COUNTRY','x',estimates=TRUE),'ggplot')
  expect_s3_class(plot_longitudinal(d,'ID','wave','x',country_var='COUNTRY',estimates=TRUE),'ggplot')
  e <- transform(d,term='x',estimate=mean,std.error=.5)
  expect_s3_class(plot_country_effects(e,'x'),'ggplot')
  expect_s3_class(plot_retention(data.frame(group='A',wave=1:2,retention_pct=c(100,50))),'ggplot')
  expect_s3_class(plot_missingness(transform(d,pct_missing=2)),'ggplot')
})
